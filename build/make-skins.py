import re, os
D = os.path.dirname(os.path.abspath(__file__)) + '/skins/'
def strip(s): return re.sub(r'/\*.*?\*/', '', s, flags=re.S)
def blocks(s):
    out, i = [], 0
    while i < len(s):
        j = s.find('{', i)
        if j < 0: break
        sel = s[i:j].strip(); depth, k = 1, j + 1
        while depth:
            if s[k] == '{': depth += 1
            elif s[k] == '}': depth -= 1
            k += 1
        out.append((sel, s[j+1:k-1])); i = k
    return out
def pre(sel, P):
    res = []
    for part in sel.split(','):
        p = part.strip()
        if not p: continue
        if p.startswith(':root'): res.append(P + p[5:])
        elif p in ('html', 'body'): res.append(P if p == 'html' else P + ' body')
        else: res.append(P + ' ' + p)
    return ','.join(res)
def build(css, P):
    o = []
    for sel, body in blocks(strip(css)):
        if sel.startswith('@keyframes') or sel.startswith('@font-face'): o.append(sel + '{' + body + '}')
        elif sel.startswith('@media'): o.append(sel + '{' + build(body, P) + '}')
        else: o.append(pre(sel, P) + '{' + body.strip() + '}')
    return '\n'.join(o)
